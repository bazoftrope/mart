import { Onest } from "next/font/google";

/**
 * Базовый шрифт дизайн-системы (Решение 35).
 *
 * Класс с CSS-переменной `--font-onest` навешивается на `<html>` в `_document.tsx`:
 * только на `<html>` её увидит токен `--font-family-base` из `:root`. `var()` внутри
 * custom property подставляется на том элементе, где свойство объявлено, поэтому
 * переменная, объявленная на потомке (`body` или обёртке в `_app`), до `:root` не
 * доходит: `font-family` на `body` становится невалидным и браузер молча рисует
 * дефолтный serif вместо Onest.
 *
 * Поэтому же в `_app.tsx` этот класс продублирован на обёртке приложения: next/font
 * собирает шрифт (генерирует `@font-face` и файлы) только для модулей, попавших в
 * страницы и `pages/_app`; ссылка из `_document` игнорируется, и без дубля CSS
 * шрифта просто не сгенерируется, а класс в HTML останется «мёртвым».
 */
export const onest = Onest({
  subsets: ["cyrillic", "latin"],
  weight: ["400", "500", "600", "700", "800"],
  variable: "--font-onest",
  display: "swap",
});
